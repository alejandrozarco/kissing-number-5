#!/usr/bin/env python3
"""Generate the κ(5) positivity modules (namespace Kissing5, kernels and `psd_step` from Kissing8.Kernel):
  lean/Kissing5/Addition3.lean, Addition4.lean          coefficient tables cA3, cA4 (k <= 8) and identities k <= 6;
  lean/Kissing5/Addition3_7.lean, ..., Addition4_8.lean  the identities for k = 7, 8 (one module each: memory);
  lean/Kissing5/Psd.lean                                 psd3, psd4 : PSD d (Zg d k) for k <= 8.
The identities are those of gen_addition8.py (solid Gegenbauer addition from R^d to R^(d-1)); every coefficient is
solved and every identity checked with sympy before it is written.
usage: python3 lean/gen/gen_addition5.py [outdir]   (default lean/Kissing5)"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gen_addition8 as G

KMAX = 8
KSPLIT = 6        # identities k <= KSPLIT in the table module, the others one module each


def header(imp, d, ks):
    return [imp, "",
            f"/-! Solid Gegenbauer addition identities from `ℝ^{d}` to `ℝ^{d - 1}`, degrees `k ∈ {ks}`.", "",
            "Generated by `lean/gen/gen_addition5.py` (every identity is first checked with sympy). Do not edit; "
            "regenerate.", "",
            f"For `x = (a, y)`, `x' = (a', y')` with `y, y' ∈ ℝ^{d - 1}`, `w = ⟪y, y'⟫`, `P = ‖y‖²`, `Q = ‖y'‖²`:",
            f"`Zg {d} k ⟪x, x'⟫ ‖x‖² ‖x'‖² = ∑_{{m ≤ k}} cA{d} k m · B(a) · B(a') · Z_m(w, P, Q)` with",
            f"`B(a) = Zg ({d} + 2m) (k - m) a ‖x‖² 1` and `Z_m` the kernel of `ℝ^{d - 1}`"
            f"{' (Chebyshev, `Zc`)' if d == 3 else ''}. -/", "",
            "namespace Kissing5", "", "open Kissing8", ""]


def identity(d, k):
    prev = "Zc m w P Q" if d == 3 else f"Zg {d - 1} m w P Q"
    return [f"theorem add{d}_{k} (a a' w P Q : ℝ) :",
            f"    Zg {d} {k} (a * a' + w) (a * a + P) (a' * a' + Q) = ∑ m ∈ Finset.range {k + 1},",
            f"      cA{d} {k} m * Zg ({d} + 2 * m) ({k} - m) a (a * a + P) 1 * Zg ({d} + 2 * m) ({k} - m) a' (a' * a' + Q) 1",
            f"        * {prev} := by",
            "  simp only [Finset.sum_range_succ, Finset.sum_range_zero, Nat.reduceAdd, Nat.reduceMul, Nat.reduceSub]",
            f"  simp only [cA{d}, Zg{', Zc' if d == 3 else ''}]",
            "  push_cast", "  ring", ""]


def table_module(d, C):
    imp = "import Kissing8.Kernel" if d == 3 else "import Kissing5.Addition3_8"
    L = header(imp, d, f"0..{KSPLIT}")
    L += [f"/-- The coefficients of the identities from `ℝ^{d}` (`0` outside `m ≤ k ≤ {KMAX}`). -/",
          f"noncomputable def cA{d} : ℕ → ℕ → ℝ"]
    for k in range(KMAX + 1):
        for m in range(k + 1):
            L.append(f"  | {k}, {m} => {G.lean_q(C[k][m])}")
    L += ["  | _, _ => 0", "",
          f"theorem cA{d}_nonneg (k m : ℕ) : 0 ≤ cA{d} k m := by", f"  unfold cA{d}", "  split <;> norm_num", ""]
    for k in range(KSPLIT + 1):
        L += identity(d, k)
    L.append("end Kissing5")
    return "\n".join(L) + "\n"


def single_module(d, k):
    imp = f"import Kissing5.Addition{d}" if k == KSPLIT + 1 else f"import Kissing5.Addition{d}_{k - 1}"
    L = header(imp, d, f"{k}") + identity(d, k) + ["end Kissing5"]
    return "\n".join(L) + "\n"


def psd_module():
    L = [f"import Kissing5.Addition4_{KMAX}", "",
         f"/-! Positive semidefiniteness of the Gegenbauer kernels of `ℝ³` and `ℝ⁴`, degrees `k ≤ {KMAX}`.", "",
         "Generated by `lean/gen/gen_addition5.py`. Induction on the dimension, as in `Kissing8.Positivity`: `psd_Zc` on",
         "`ℝ²`, then `psd_step` with the identities `add3_k`, `add4_k`. -/", "",
         "namespace Kissing5", "", "open Kissing8", ""]
    for d in (3, 4):
        prev = "fun m _ => psd_Zc m" if d == 3 else "fun m hm => psd3 m (by rw [Finset.mem_range] at hm; omega)"
        zp = "Zc" if d == 3 else "(Zg 3)"
        L += [f"theorem psd{d} (k : ℕ) (hk : k ≤ {KMAX}) : PSD {d} (Zg {d} k) := by", "  interval_cases k"]
        for k in range(KMAX + 1):
            L += [f"  · exact psd_step (d := {d - 1}) (K := {k}) (Zg {d} {k}) {zp} (cA{d} {k})",
                  f"      (fun m a r => Zg ({d} + 2 * m) ({k} - m) a r 1) (cA{d}_nonneg {k}) ({prev}) (add{d}_{k})"]
        L.append("")
    L.append("end Kissing5")
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "Kissing5")
    for d in (3, 4):
        C = [G.coeffs(d, k) for k in range(KMAX + 1)]
        open(os.path.join(out, f"Addition{d}.lean"), "w", encoding="utf-8").write(table_module(d, C))
        for k in range(KSPLIT + 1, KMAX + 1):
            open(os.path.join(out, f"Addition{d}_{k}.lean"), "w", encoding="utf-8").write(single_module(d, k))
        print(f"Addition{d}: {sum(len(c) for c in C)} coefficients, all >= 0, identities k <= {KMAX} checked")
    open(os.path.join(out, "Psd.lean"), "w", encoding="utf-8").write(psd_module())
    print("Psd.lean written")
